#!/usr/bin/env python3
"""Imports the Signal glyph set (design/signal/assets/icons) into ios/Shared/Glyphs.xcassets and writes the `Glyph`
enum (ios/Shared/Design/Glyph.swift). Re-run it whenever glyphs are added to the folder or its index.json.

Each glyph becomes a template image set with Preserve Vector Data, so it takes the foreground colour and stays sharp
at any size. The SVGs draw in `currentColor`, which the importer makes black (a template uses only the alpha). Parts
drawn in white (the check knocked out of a filled shield) become a mask, so they stay holes in any colour. Inline
`style` declarations become presentation attributes, which every SVG renderer reads.

    python3 ios/scripts/import-glyphs.py
"""

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ICONS = ROOT / "design" / "signal" / "assets" / "icons"
CATALOG = ROOT / "ios" / "Shared" / "Glyphs.xcassets"
SWIFT = ROOT / "ios" / "Shared" / "Design" / "Glyph.swift"

WHITE = {"#fff", "#ffffff", "white"}
ELEMENT = re.compile(r"<(path|circle|rect|ellipse|line|polyline|polygon)\b([^>]*?)(/?)>(?:</\1>)?")
STYLE = re.compile(r'\sstyle="([^"]*)"')


def attributes_from_style(attrs: str) -> str:
    """`style="stroke: #fff; stroke-width: 2.4"` becomes `stroke="#fff" stroke-width="2.4"`."""
    m = STYLE.search(attrs)
    if not m:
        return attrs
    pairs = [p.split(":", 1) for p in m.group(1).split(";") if ":" in p]
    extra = "".join(f' {k.strip()}="{v.strip()}"' for k, v in pairs)
    return attrs[: m.start()] + extra + attrs[m.end() :]


def is_white(attrs: str) -> bool:
    for key in ("stroke", "fill"):
        m = re.search(rf'\s{key}="([^"]*)"', attrs)
        if m and m.group(1).strip().lower() in WHITE:
            return True
    return False


def convert(svg: str, name: str) -> str:
    svg = svg.replace("currentColor", "#000")
    open_tag = re.match(r"<svg\b[^>]*>", svg)
    if not open_tag:
        raise ValueError(f"{name}: no <svg> element")
    head, body = open_tag.group(0), svg[open_tag.end() :].replace("</svg>", "")
    shapes, holes = [], []
    for m in ELEMENT.finditer(body):
        attrs = attributes_from_style(m.group(2))
        element = f"<{m.group(1)}{attrs}/>"
        (holes if is_white(attrs) else shapes).append(element)
    leftover = ELEMENT.sub("", body).strip()
    if leftover:
        raise ValueError(f"{name}: unsupported markup {leftover[:60]!r}")
    if not holes:
        return head + "".join(shapes) + "</svg>\n"
    # White parts cut through what is under them: a mask, white where the glyph shows and black where it is cut.
    cut = "".join(re.sub(r'\s(stroke|fill)="(#fff|#ffffff|white)"', r' \1="#000"', h, flags=re.I) for h in holes)
    mask = (
        f'<mask id="cut" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24">'
        f'<rect width="24" height="24" fill="#fff" stroke="none"/>{cut}</mask>'
    )
    return head + mask + f'<g mask="url(#cut)">' + "".join(shapes) + "</g></svg>\n"


def case_name(name: str) -> str:
    parts = re.split(r"[-_]", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return f"`{out}`" if out in {"default", "repeat", "return", "switch", "case", "in", "is"} else out


def main() -> int:
    index = json.loads((ICONS / "index.json").read_text())
    names = sorted({entry["name"]: entry["file"] for entry in index}.items())
    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    CATALOG.mkdir(parents=True)
    (CATALOG / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    for name, file in names:
        svg = convert((ICONS / file).read_text(), name)
        folder = CATALOG / f"{name}.imageset"
        folder.mkdir()
        (folder / f"{name}.svg").write_text(svg)
        contents = {
            "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }
        (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")

    cases = "\n".join(f'    case {case_name(n)} = "{n}"' for n, _ in names)
    SWIFT.write_text(
        f"""import SwiftUI

// Generated by ios/scripts/import-glyphs.py from design/signal/assets/icons/index.json; do not edit by hand.

/// The Signal glyphs (Shared/Glyphs.xcassets): 24 grid, 1.6 stroke, round caps and joins, one weight. Template images,
/// so they take the foreground style: `ink-2` in rows, `on-field` on fields, `ink-faint` for chevrons.
enum Glyph: String, CaseIterable {{
{cases}
}}
"""
    )
    print(f"{len(names)} glyphs into {CATALOG.relative_to(ROOT)} and {SWIFT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
