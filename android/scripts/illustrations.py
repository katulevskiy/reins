#!/usr/bin/env python3
"""Converts the Signal illustrations (pond, kite) into Android VectorDrawables.

design/signal/assets/illustrations/<name>-light.svg -> res/drawable/signal_<name>.xml
design/signal/assets/illustrations/<name>-dark.svg  -> res/drawable-night/signal_<name>.xml

The drawings are filled paths and circles with a fill colour and an opacity; that is all this handles.

Usage: python3 android/scripts/illustrations.py
"""

import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design/signal/assets/illustrations"
RES = ROOT / "android/app/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"
NAMES = ["pond", "kite"]


def num(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def style(el) -> dict:
    out = {}
    for decl in (el.get("style") or "").split(";"):
        if ":" in decl:
            k, v = decl.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def color(value: str) -> str:
    v = value.strip().lower()
    if not v.startswith("#"):
        raise SystemExit(f"unsupported colour {value!r}")
    v = v[1:]
    if len(v) == 3:
        v = "".join(ch * 2 for ch in v)
    return "#FF" + v.upper()


def path_d(el) -> str:
    tag = el.tag.replace(SVG, "")
    if tag == "path":
        return " ".join(el.get("d").split())
    if tag == "circle":
        cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
        return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0 1,0 {num(2 * r)},0a{num(r)},{num(r)} 0 1,0 {num(-2 * r)},0z"
    raise SystemExit(f"unsupported element <{tag}>")


def convert(svg: pathlib.Path, out: pathlib.Path) -> None:
    root = ET.parse(svg).getroot()
    _, _, w, h = (float(x) for x in root.get("viewBox").split())
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by android/scripts/illustrations.py from design/signal/assets/illustrations/{svg.name}. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{num(w)}dp"',
        f'    android:height="{num(h)}dp"',
        f'    android:viewportWidth="{num(w)}"',
        f'    android:viewportHeight="{num(h)}">',
    ]
    for el in root:
        st = style(el)
        fill = st.get("fill", el.get("fill"))
        if fill is None or fill == "none":
            continue
        opacity = float(st.get("opacity", el.get("opacity", "1")))
        alpha = "" if opacity >= 1 else f' android:fillAlpha="{num(opacity)}"'
        lines.append(f'    <path android:fillColor="{color(fill)}"{alpha} android:pathData="{path_d(el)}" />')
    lines.append("</vector>")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(out.relative_to(ROOT))


def main() -> None:
    for name in NAMES:
        convert(SRC / f"{name}-light.svg", RES / "drawable" / f"signal_{name}.xml")
        convert(SRC / f"{name}-dark.svg", RES / "drawable-night" / f"signal_{name}.xml")


if __name__ == "__main__":
    main()
